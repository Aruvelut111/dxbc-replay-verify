"""Baseline / Modified / Rollback verification for dxbc-replay-verify.

The claim under test is narrow and mechanical:

  1. BASELINE   the compiled writer, replayed on hardware, reproduces the
                CPU-side expectation byte for byte;
  2. MODIFIED   patching one float32 in the pixel CB0 (gain 1.0 -> 1.5)
                produces a *different* volume that again matches its own
                expectation, and the change is recorded (before/after);
  3. ROLLBACK   patching back to 1.0 lands on the cached baseline identity
                without re-executing the writer, byte-identical to step 1;
  4. FORCE      re-executing the baseline from scratch is deterministic;
  5. FAILURE    a manifest that violates the draw profile fails loudly and
                the previous success is retained, not overwritten.

Run from the repository root:

    python tests/test_baseline_modified_rollback.py

Exit code 0 = every check passed. No third-party dependencies; the demo
inputs are generated by demo/build_demo.py if missing.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from demo.expected_volume import expected_volume, load_source_texture  # noqa: E402
from replay.controller import rebuild  # noqa: E402

MANIFEST = ROOT / "demo" / "build" / "manifest.json"
TEXTURE = ROOT / "demo" / "build" / "source_texture.bin"
PYTHON = sys.executable

BASELINE_GAIN = 1.0
MODIFIED_GAIN = 1.5

PATCH = [
    {
        "stage": "pixel",
        "slot": 0,
        "byte_offset": 0,
        "type": "float32",
        "value": MODIFIED_GAIN,
        "symbol": "g_gain",
    }
]

checks: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    checks.append((name, bool(ok), detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"  -- {detail}" if detail else ""))


def ensure_demo_inputs() -> None:
    if MANIFEST.is_file() and TEXTURE.is_file():
        return
    print("demo inputs missing; building them first ...")
    subprocess.run([PYTHON, str(ROOT / "demo" / "build_demo.py")], check=True, cwd=ROOT)


def broken_manifest(tmp: Path) -> Path:
    """Same draw, but without the expected_writer_output row.

    Paths are rewritten to absolute so the copy can live outside demo/build/.
    """
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8-sig"))
    manifest["textures"] = [
        r for r in manifest["textures"] if r.get("role") != "expected_writer_output"
    ]
    for section in ("shaders", "constant_buffers", "vertex_buffers", "textures"):
        for row in manifest[section]:
            for key in ("path", "raw_path"):
                if row.get(key) and not Path(row[key]).is_absolute():
                    row[key] = str((MANIFEST.parent / row[key]).resolve())
    out = tmp / "manifest_without_reference_row.json"
    out.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return out


def main() -> int:
    ensure_demo_inputs()
    texture = load_source_texture(TEXTURE)
    expected_baseline = expected_volume(BASELINE_GAIN, texture)
    expected_modified = expected_volume(MODIFIED_GAIN, texture)

    with tempfile.TemporaryDirectory(prefix="dxbc-bmr-") as tmp_name:
        root = Path(tmp_name) / "checks"

        print("\n[1] BASELINE  (gain 1.0, hardware replay)")
        base = rebuild(str(MANIFEST), str(root))
        base_bytes = Path(base["output"]["path"]).read_bytes()
        check("status == rebuilt", base["status"] == "rebuilt", base["status"])
        check("reference EXACT_REFERENCE_MATCHED",
              base.get("reference_status") == "EXACT_REFERENCE_MATCHED",
              str(base.get("reference_status")))
        check("4096/4096 voxels identical",
              base["reference_comparison"]["identical_packed_voxels"] == 4096)
        check("output bytes == CPU expectation", base_bytes == expected_baseline)
        baseline_sha = base["output"]["sha256"]
        print(f"         sha256 = {baseline_sha}")

        print("\n[2] MODIFIED  (CB0 gain 1.0 -> 1.5)")
        mod = rebuild(str(MANIFEST), str(root), overrides=PATCH)
        mod_bytes = Path(mod["output"]["path"]).read_bytes()
        check("status == rebuilt (identity changed)", mod["status"] == "rebuilt", mod["status"])
        check("different cache identity than baseline",
              mod["identity"] != base["identity"])
        check("output bytes == CPU expectation @1.5", mod_bytes == expected_modified)
        check("output differs from baseline", mod_bytes != base_bytes)
        change = mod["changes"][0]
        check("CB change recorded 1.0 -> 1.5",
              change["before"] == BASELINE_GAIN and change["after"] == MODIFIED_GAIN,
              f"{change['before']} -> {change['after']} @ offset {change['byte_offset']}")
        print(f"         sha256 = {mod['output']['sha256']}")

        print("\n[3] ROLLBACK  (CB0 gain 1.5 -> 1.0)")
        back = rebuild(str(MANIFEST), str(root),
                       overrides=[dict(PATCH[0], value=BASELINE_GAIN)])
        back_bytes = Path(back["output"]["path"]).read_bytes()
        check("status == cache_hit (writer not re-executed)",
              back["status"] == "cache_hit", back["status"])
        check("draw_executed_this_call is False", back["draw_executed_this_call"] is False)
        check("bytes identical to baseline", back_bytes == base_bytes)
        check("sha256 identical to baseline",
              back["output"]["sha256"] == baseline_sha)
        check("reference MATCHED again",
              back.get("reference_status") == "EXACT_REFERENCE_MATCHED")

        print("\n[4] FORCE     (re-execute baseline from scratch)")
        forced = rebuild(str(MANIFEST), str(root), force=True)
        forced_bytes = Path(forced["output"]["path"]).read_bytes()
        check("status == rebuilt", forced["status"] == "rebuilt", forced["status"])
        check("deterministic: same bytes as first baseline",
              forced_bytes == base_bytes and forced["output"]["sha256"] == baseline_sha)

        print("\n[5] FAILURE   (manifest without the reference row)")
        before_state = json.loads((root / "STATE.json").read_text(encoding="utf-8"))
        bad = rebuild(str(broken_manifest(Path(tmp_name))), str(root))
        check("status == failed_retaining_last_success",
              bad["status"] == "failed_retaining_last_success", bad["status"])
        check("last_success retained (not clobbered)",
              bad["last_success"] is not None
              and bad["last_success"]["output"]["sha256"] == baseline_sha)
        after_state = json.loads((root / "STATE.json").read_text(encoding="utf-8"))
        check("STATE.json last_success unchanged",
              after_state["last_success"]["output"]["sha256"]
              == before_state["last_success"]["output"]["sha256"])
        check("error text present", bool(bad.get("error")))

    failed = [name for name, ok, _ in checks if not ok]
    print(f"\n{len(checks) - len(failed)}/{len(checks)} checks passed")
    if failed:
        print("FAILED: " + ", ".join(failed))
        return 1
    print("ALL CHECKS PASSED")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
